#!/usr/bin/env python3
"""Compile src/progression.yaml (the Ember Forge) into KubeJS scripts, and check it.

  python3 tools/dump_recipes.py            # once, after the mod jars are cached (.cache/recipes.json)
  python3 tools/build_progression.py       # writes the scripts below; exits non-zero if a check fails

Writes
  pack/kubejs/startup_scripts/remnants_forge_items.js     custom items (tinted textures, rarity, stack size)
  pack/kubejs/client_scripts/remnants/forge_tooltips.js   their lore lines
  pack/kubejs/server_scripts/remnants/forge.js            removes the original recipes, adds the forged ones
  pack/kubejs/assets/remnants/lang/en_us.json             item names (merged; other keys kept)

Retiered and edited recipes are rebuilt from the mod's own JSON (read from the jar), so special recipe types
(backpack upgrades that keep their contents, storage tier upgrades, smithing...) keep their type and only their
ingredients change. They get new ids under remnants:retier/<mod>/<path>; the originals are removed.

Checks: every item id the spec names exists (a lang key or an item model in some jar, or a custom item); every
recipe an edit names exists and really changes; every custom item has a recipe; every material a new recipe asks
for can be obtained (some recipe still makes it, a loot table or loot bag drops it, or it is a known boss drop).
"""
import importlib.util
import json
import re
import sys
import zipfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "src" / "progression.yaml"
KJS = ROOT / "pack" / "kubejs"
ITEMS_JS = KJS / "startup_scripts" / "remnants_forge_items.js"
TIPS_JS = KJS / "client_scripts" / "remnants" / "forge_tooltips.js"
RECIPES_JS = KJS / "server_scripts" / "remnants" / "forge.js"
LANG = KJS / "assets" / "remnants" / "lang" / "en_us.json"
INDEX = ROOT / ".cache" / "recipes.json"
HEADER = "// Generated by tools/build_progression.py from src/progression.yaml. Do not edit; edit the YAML.\n"

# Dropped by code, not by a loot table: Runeborn hands these out when a Sovereign (or the vanilla boss with a relic)
# dies; Deeper Darker's Warden drops its heart through its own loot code.
CODE_DROPS = {f"runeborn:relic_{b}" for b in ("dusk_rider", "varghast", "sylvara", "kaelthar", "ysolde", "morgrath",
                                               "vaelorn", "warden", "elder_guardian", "wither", "ender_dragon")}
CODE_DROPS |= {"runeborn:hallowed_tear", "deeperdarker:heart_of_the_deep", "deeperdarker:warden_carapace",
               "minecraft:nether_star", "minecraft:dragon_breath",
               "minecraft:enchanted_book"}   # enchanting tables and librarians, not loot tables


def _dump_recipes():
    spec = importlib.util.spec_from_file_location("dump_recipes", ROOT / "tools" / "dump_recipes.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


class Jars:
    """Read original recipe JSON, item models and loot tables from the cached jars."""

    def __init__(self):
        dr = _dump_recipes()
        self.jars = {j.name: j for j in dr.included_jars()}
        self.vanilla = dr.VANILLA
        self.client = ROOT / ".cache" / "vanilla-client-1.21.1-extra.jar"
        self._zips = {}

    def zip(self, path):
        if path not in self._zips:
            self._zips[path] = zipfile.ZipFile(path)
        return self._zips[path]

    def all_zips(self):
        paths = list(self.jars.values()) + [p for p in (self.vanilla, self.client) if p.exists()]
        return [self.zip(p) for p in paths]

    def recipe_json(self, rid, entry):
        z = self.zip(self.jars[entry["jar"]] if entry["jar"] in self.jars else self.vanilla)
        ns, path = rid.split(":", 1)
        for base in ("recipe", "recipes"):
            try:
                return json.loads(z.read(f"data/{ns}/{base}/{path}.json"))
            except KeyError:
                continue
        raise KeyError(rid)

    def known_items(self):
        known = set()
        for z in self.all_zips():
            for n in z.namelist():
                m = re.match(r"assets/([a-z0-9_.-]+)/models/item/(.+)\.json$", n)
                if m:
                    known.add(f"{m.group(1)}:{m.group(2)}")
        for f in (ROOT / "research" / "registry").glob("*_en_us.json"):
            try:
                data = json.loads(f.read_text())
            except json.JSONDecodeError:
                continue
            for k in data:
                p = k.split(".")
                if len(p) == 3 and p[0] in ("item", "block"):
                    known.add(f"{p[1]}:{p[2]}")
        return known

    def loot_text(self):
        """Every loot table (mods, vanilla, the pack's own datapack) and the loot-bag source, as one string."""
        parts = []
        for z in self.all_zips():
            for n in z.namelist():
                if "/loot_table" in n and n.endswith(".json"):
                    parts.append(z.read(n).decode("utf8", "ignore"))
        for f in (KJS / "data").rglob("*.json"):
            if "loot_table" in f.as_posix():
                parts.append(f.read_text(errors="ignore"))
        bags = ROOT / "src" / "data" / "loot_bags.yaml"
        if bags.exists():
            parts.append(bags.read_text())
        return "\n".join(parts)


def ingredient(spec):
    """'#c:ingots/iron' -> {'tag': ...}; 'mod:item' -> {'item': ...}."""
    return {"tag": spec[1:]} if spec.startswith("#") else {"item": spec}


def ingredient_key(node):
    if isinstance(node, dict) and set(node) <= {"item", "count"} and isinstance(node.get("item"), str):
        return node["item"]
    if isinstance(node, dict) and set(node) == {"tag"}:
        return "#" + node["tag"]
    return None


OUTPUT_KEYS = {"result", "results", "output", "type", "neoforge:conditions", "conditions", "category", "group",
               "pattern", "show_notification", "transitional_item", "transitionalItem"}


def apply_map(node, mapping):
    """Swap ingredients in place everywhere except outputs. Returns how many were swapped."""
    n = 0
    if isinstance(node, list):
        for i, v in enumerate(node):
            k = ingredient_key(v)
            if k in mapping:
                node[i] = ingredient(mapping[k])
                n += 1
            else:
                n += apply_map(v, mapping)
    elif isinstance(node, dict):
        for key in list(node):
            if key in OUTPUT_KEYS:
                continue
            v = node[key]
            k = ingredient_key(v)
            if k in mapping:
                node[key] = ingredient(mapping[k])
                n += 1
            else:
                n += apply_map(v, mapping)
    return n


def ingredients_of(node, out):
    if isinstance(node, list):
        for v in node:
            ingredients_of(v, out)
    elif isinstance(node, dict):
        k = ingredient_key(node)
        if k:
            out.append(k)
            return out
        for key, v in node.items():
            if key not in OUTPUT_KEYS:
                ingredients_of(v, out)
    return out


def result_of(r):
    for key in ("result", "results", "output"):
        v = r.get(key)
        if isinstance(v, list):
            v = v[0] if v else None
        if isinstance(v, dict):
            return v.get("id") or v.get("item"), v.get("count", 1)
        if isinstance(v, str):
            return v, 1
    return None, 1


def js(v):
    return json.dumps(v, ensure_ascii=False)


def kube_crafting(rid, r, keep):
    """A crafting recipe as KubeJS shaped/shapeless with keepIngredient (only simple ingredients allowed)."""
    res, count = result_of(r)
    out = f"Item.of({js(res)}, {count})" if count != 1 else js(res)
    kind = r["type"].split(":")[-1]
    if kind == "crafting_shaped":
        keys = {}
        for k, v in r["key"].items():
            s = ingredient_key(v)
            if not s:
                sys.exit(f"{rid}: keep needs simple ingredients, key {k} is {v}")
            keys[k] = s
        line = f"event.shaped({out}, {js(r['pattern'])}, {js(keys)})"
    elif kind == "crafting_shapeless":
        ings = []
        for v in r["ingredients"]:
            s = ingredient_key(v)
            if not s:
                sys.exit(f"{rid}: keep needs simple ingredients, got {v}")
            ings.append(s)
        line = f"event.shapeless({out}, {js(ings)})"
    else:
        sys.exit(f"{rid}: keep only works on crafting recipes, not {r['type']}")
    for k in keep:
        line += f".keepIngredient({js(k)})"
    return line + f".id({js(rid)})"


def main():
    spec = yaml.safe_load(SPEC.read_text())
    if not INDEX.exists():
        sys.exit("run tools/dump_recipes.py first")
    index = json.loads(INDEX.read_text())
    jars = Jars()
    known = jars.known_items() | {it["id"] for it in spec["items"]}
    custom = {it["id"] for it in spec["items"]}
    errors = []

    def need(item, where):
        if not item.startswith("#") and item not in known:
            errors.append(f"unknown item {item} ({where})")

    # ---- retier: whole mods onto the alloys ----
    rebuilt = {}            # original id -> new recipe json
    per_mod = {}
    for rule in spec.get("retier", []):
        mapping = {k: v for k, v in rule["map"].items()}
        for v in mapping.values():
            need(v, "retier map")
        for rid, entry in index.items():
            ns, path = rid.split(":", 1)
            if ns not in rule["mods"] or any(s in path for s in rule.get("skip", [])):
                continue
            try:
                r = jars.recipe_json(rid, entry)
            except KeyError:
                continue
            r.pop("neoforge:conditions", None)
            if apply_map(r, mapping):
                rebuilt[rid] = r
                per_mod[ns] = per_mod.get(ns, 0) + 1

    # ---- edits: single recipes ----
    keeps = {}
    for e in spec.get("edits", []):
        ids = [e["id"]] if "id" in e else sorted(k for k in index if re.search(e["match"], k))
        if not ids or ("id" in e and e["id"] not in index):
            errors.append(f"edit names no recipe: {e.get('id') or e.get('match')}")
            continue
        for rid in ids:
            r = rebuilt.get(rid) or jars.recipe_json(rid, index[rid])
            r.pop("neoforge:conditions", None)
            before = json.dumps(r, sort_keys=True)
            if e.get("map"):
                for v in e["map"].values():
                    need(v, rid)
                apply_map(r, e["map"])
            if e.get("pattern"):
                r["pattern"] = e["pattern"]
                r["key"] = {k: ingredient(v) for k, v in e["key"].items()}
                for v in e["key"].values():
                    need(v, rid)
                used = set("".join(e["pattern"])) - {" "}
                if used != set(e["key"]):
                    errors.append(f"{rid}: pattern letters {sorted(used)} vs key {sorted(e['key'])}")
            if e.get("result_count"):
                r["result"]["count"] = int(e["result_count"])
            if e.get("add"):
                r.setdefault("ingredients", []).extend(ingredient(a) for a in e["add"])
                for v in e["add"]:
                    need(v, rid)
            if json.dumps(r, sort_keys=True) == before:
                if "id" in e:
                    errors.append(f"edit changes nothing: {rid}")
                continue                      # a pattern edit may match recipes the swap doesn't apply to
            rebuilt[rid] = r
            if e.get("keep"):
                keeps[rid] = e["keep"]

    # ---- new recipes ----
    new_lines = []
    produced = set()
    asked = {}
    for rec in spec.get("recipes", []):
        rid = rec["id"]
        if "json" in rec:
            r = rec["json"]
            res, _ = result_of(r)
            new_lines.append(f"event.custom({js(r)}).id({js(rid)})")
            for i in ingredients_of(r, []):
                asked.setdefault(i, rid)
        else:
            res = rec["result"][0] if isinstance(rec["result"], list) else rec["result"]
            count = rec["result"][1] if isinstance(rec["result"], list) else 1
            if "shaped" in rec:
                r = {"type": "minecraft:crafting_shaped", "pattern": rec["shaped"],
                     "key": {k: ingredient(v) for k, v in rec["key"].items()},
                     "result": {"id": res, "count": count}}
                used = set("".join(rec["shaped"])) - {" "}
                if used != set(rec["key"]):
                    errors.append(f"{rid}: pattern letters {sorted(used)} vs key {sorted(rec['key'])}")
            else:
                r = {"type": "minecraft:crafting_shapeless", "ingredients": [ingredient(i) for i in rec["shapeless"]],
                     "result": {"id": res, "count": count}}
            new_lines.append(kube_crafting(rid, r, rec.get("keep", [])))
            for i in ingredients_of(r, []):
                asked.setdefault(i, rid)
        produced.add(res)
        need(res, rid)
        for i in ingredients_of(r, []):
            need(i, rid)
    for rid, r in rebuilt.items():
        res, _ = result_of(r)
        if res:
            produced.add(res)
        for i in ingredients_of(r, []):
            need(i, rid)
            if i in custom or rid in keeps:
                asked.setdefault(i, rid)

    # ---- every custom item is made somewhere; every asked-for material can be had ----
    for it in spec["items"]:
        if it["id"] not in produced:
            errors.append(f"nothing makes {it['id']}")
    removed = set(rebuilt)
    makers = {}
    for rid, entry in index.items():
        res = entry.get("result")
        if rid not in removed and isinstance(res, str):
            makers.setdefault(res, rid)
    loot = jars.loot_text()
    for item, where in sorted(asked.items()):
        if item.startswith("#") or item in custom or item in produced or item in makers or item in CODE_DROPS:
            continue
        if f'"{item}"' in loot or f"{item}," in loot or f"[{item}" in loot:
            continue
        errors.append(f"cannot be obtained: {item} (asked by {where})")

    if errors:
        print("\n".join(errors))
        sys.exit(1)

    # ---- write ----
    rarity = {"common": "common", "uncommon": "uncommon", "rare": "rare", "epic": "epic"}
    lines = [HEADER, "// The Ember Forge's materials. Textures are vanilla's (or kubejs/assets/remnants/textures/item/), tinted.",
             "", "StartupEvents.registry('item', function (event) {"]
    for it in spec["items"]:
        line = f"  event.create({js(it['id'])}).texture({js(it['texture'])}).color(0, {it['tint']:#08x})"
        if it.get("rarity"):
            line += f".rarity({js(rarity[it['rarity']])})"
        if it.get("stack"):
            line += f".maxStackSize({int(it['stack'])})"
        lines.append(line)
    lines.append("})")
    ITEMS_JS.write_text("\n".join(lines) + "\n")

    tips = [HEADER, "ItemEvents.modifyTooltips(function (event) {"]
    for it in spec["items"]:
        if it.get("lore"):
            texts = ", ".join(f"Text.gray({js(t)})" for t in it["lore"])
            tips.append(f"  event.add({js(it['id'])}, [{texts}])")
    tips.append("})")
    TIPS_JS.parent.mkdir(parents=True, exist_ok=True)
    TIPS_JS.write_text("\n".join(tips) + "\n")

    lang = json.loads(LANG.read_text()) if LANG.exists() else {}
    for it in spec["items"]:
        ns, path = it["id"].split(":")
        lang[f"item.{ns}.{path}"] = it["name"]
    LANG.write_text(json.dumps(dict(sorted(lang.items())), indent=2, ensure_ascii=False) + "\n")

    out = [HEADER,
           "// The Ember Forge: six tiers of alloys tied to the story (see design/PROGRESSION.md). Retiered recipes are",
           "// the mods' own, rebuilt with the forge's materials; their originals are removed.", "",
           "ServerEvents.recipes(function (event) {",
           f"  {js(sorted(removed))}.forEach(function (id) {{ event.remove({{ id: id }}) }})"]
    for rid in sorted(rebuilt):
        ns, path = rid.split(":", 1)
        new_id = f"remnants:retier/{ns}/{path}"
        if rid in keeps:
            out.append("  " + kube_crafting(new_id, rebuilt[rid], keeps[rid]))
        else:
            out.append(f"  event.custom({js(rebuilt[rid])}).id({js(new_id)})")
    out += ["  " + l for l in new_lines]
    out.append("})")
    RECIPES_JS.write_text("\n".join(out) + "\n")

    print(f"{len(spec['items'])} items, {len(new_lines)} new recipes, {len(rebuilt)} rebuilt "
          f"({', '.join(f'{k} {v}' for k, v in sorted(per_mod.items()))}; {len(spec.get('edits', []))} edits)")


if __name__ == "__main__":
    main()
